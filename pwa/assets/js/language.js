let currentLang = localStorage.getItem("language") || "nl";
let observer = null;

function updateFlagStyles(lang) {
  const btnNl = document.getElementById("lang-btn-nl");
  const btnEn = document.getElementById("lang-btn-en");
  
  if (btnNl && btnEn) {
    if (lang === "nl") {
      btnNl.style.opacity = "1";
      btnNl.style.filter = "grayscale(0%)";
      btnNl.style.transform = "scale(1.2)";
      btnEn.style.opacity = "0.4";
      btnEn.style.filter = "grayscale(100%)";
      btnEn.style.transform = "scale(1.0)";
    } else {
      btnNl.style.opacity = "0.4";
      btnNl.style.filter = "grayscale(100%)";
      btnNl.style.transform = "scale(1.0)";
      btnEn.style.opacity = "1";
      btnEn.style.filter = "grayscale(0%)";
      btnEn.style.transform = "scale(1.2)";
    }
  }
}

function translateDOM(lang) {
  const walk = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      const originalText = node.nodeValue.trim();
      if (originalText) {
        for (const key of Object.keys(translations.nl)) {
          const nlVal = translations.nl[key];
          const enVal = translations.en[key];
          
          if (originalText === nlVal || originalText === enVal) {
            const targetVal = lang === "nl" ? nlVal : enVal;
            if (originalText !== targetVal) {
              node.nodeValue = node.nodeValue.replace(originalText, targetVal);
            }
            break;
          }
        }
      }
    } else {
      if (["SCRIPT", "STYLE", "IFRAME", "TEXTAREA"].includes(node.nodeName)) return;

      if (node.placeholder) {
        const originalPH = node.placeholder.trim();
        for (const key of Object.keys(translations.nl)) {
          const nlVal = translations.nl[key];
          const enVal = translations.en[key];
          if (originalPH === nlVal || originalPH === enVal) {
            const targetVal = lang === "nl" ? nlVal : enVal;
            if (originalPH !== targetVal) {
              node.placeholder = targetVal;
            }
            break;
          }
        }
      }

      for (let child of node.childNodes) {
        walk(child);
      }
    }
  };

  if (observer) observer.disconnect();
  walk(document.body);
  if (observer) {
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
}

function initLanguage() {
  const btnNl = document.getElementById("lang-btn-nl");
  const btnEn = document.getElementById("lang-btn-en");

  if (btnNl) {
    btnNl.onclick = (e) => {
      e.stopPropagation();
      currentLang = "nl";
      localStorage.setItem("language", currentLang);
      updateFlagStyles(currentLang);
      translateDOM(currentLang);
    };
  }

  if (btnEn) {
    btnEn.onclick = (e) => {
      e.stopPropagation();
      currentLang = "en";
      localStorage.setItem("language", currentLang);
      updateFlagStyles(currentLang);
      translateDOM(currentLang);
    };
  }

  updateFlagStyles(currentLang);
  translateDOM(currentLang);

  observer = new MutationObserver(() => {
    translateDOM(currentLang);
  });

  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initLanguage);
} else {
  initLanguage();
}
